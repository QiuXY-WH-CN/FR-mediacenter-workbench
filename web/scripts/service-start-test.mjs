// Isolated Windows lifecycle integration: no production port, database, tunnel, or credentials are touched.
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp, mkdir, readFile, writeFile, rm} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

if(process.platform!=='win32') throw new Error('This lifecycle test requires Windows PowerShell and CIM.');
const project=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const helper=path.join(project,'scripts/start-services.ps1');
const quote=value=>"'"+value.replaceAll("'","''")+"'";
const powershell=process.env.STARTUP_TEST_POWERSHELL||'powershell.exe';
const port=8893;
await mkdir(path.join(project,'.local'),{recursive:true});
const sandbox=await mkdtemp(path.join(project,'.local','startup with spaces '));
const scripts=path.join(sandbox,'scripts');
const local=path.join(sandbox,'.local');
await mkdir(scripts,{recursive:true});
await mkdir(local,{recursive:true});
const ownedIds=new Set();
const runPs=body=>new Promise((resolve,reject)=>{
  const cmd=`$ErrorActionPreference='Stop'; . ${quote(helper)}; ${body}`;
  const child=spawn(powershell,['-NoProfile','-NonInteractive','-ExecutionPolicy','Bypass','-Command',cmd],{windowsHide:true});
  let stdout='',stderr='';
  child.stdout.on('data',chunk=>stdout+=chunk);
  child.stderr.on('data',chunk=>stderr+=chunk);
  child.on('error',reject);
  child.on('exit',code=>resolve({code,stdout,stderr}));
});
const resultOf=async(body)=>{
  const result=await runPs(body);
  assert.equal(result.code,0,result.stderr||result.stdout);
  const line=result.stdout.split(/\r?\n/).find(line=>line.startsWith('@@RESULT@@'));
  assert.ok(line,result.stdout);
  return JSON.parse(line.slice(10));
};
const startBody=`$r=Start-WorkbenchOrigin -WebRoot ${quote(sandbox)} -Port ${port}; Write-Output ('@@RESULT@@'+($r|ConvertTo-Json -Compress))`;
const append=`import{appendFileSync}from'node:fs';appendFileSync('.local/order.txt',`;
const build=`${append}'build\\n');`;
const backup=`${append}'backup\\n');`;
const server=`import http from'node:http';${append}'serve\\n');http.createServer((req,res)=>{res.setHeader('Content-Type','application/json');res.end(JSON.stringify({version:'v1.0.0',initialized:true,departments:['test']}))}).listen(Number(process.env.PORT),'127.0.0.1');`;
await writeFile(path.join(scripts,'build.mjs'),build);
await writeFile(path.join(scripts,'backup.mjs'),backup);
await writeFile(path.join(scripts,'dev.mjs'),server);
await writeFile(path.join(local,'preview.db'),'isolated backup marker, never a real database');
let foreign;
try {
  const noListener=await resultOf(`Write-Output ('@@RESULT@@'+(@(Get-WorkbenchListeners -Port ${port}).Count|ConvertTo-Json -Compress))`);
  assert.equal(noListener,0,'Test port is occupied; this test never stops existing services.');
  const foreignScript=path.join(sandbox,'foreign.mjs');
  await writeFile(foreignScript,`import http from'node:http';http.createServer((req,res)=>res.end('foreign')).listen(${port},'127.0.0.1',()=>console.log('READY'));`);
  foreign=spawn(process.execPath,[foreignScript],{windowsHide:true});
  await new Promise((resolve,reject)=>{foreign.stdout.once('data',resolve);foreign.once('error',reject);foreign.once('exit',code=>reject(new Error('Foreign fixture exited: '+code)));});
  const refusal=await runPs(startBody);
  assert.notEqual(refusal.code,0,'A foreign listener must be rejected.');
  assert.ok(refusal.stderr.includes(String(foreign.pid)),'Refusal identifies the occupied PID without printing command lines.');
  assert.equal((await fetch(`http://127.0.0.1:${port}`)).status,200,'Foreign process was preserved.');
  foreign.kill();
  await new Promise(resolve=>foreign.once('exit',resolve));
  foreign=null;
  const first=await resultOf(startBody);
  ownedIds.add(first.serverId);
  assert.equal(first.reused,false);
  assert.equal(await readFile(path.join(local,'order.txt'),'utf8'),'build\nbackup\nserve\n','Backup completes before starting the server.');
  const reused=await resultOf(startBody);
  assert.equal(reused.serverId,first.serverId);
  assert.equal(reused.reused,true,'Repeated launcher runs are idempotent.');
  assert.equal(await readFile(path.join(local,'order.txt'),'utf8'),'build\nbackup\nserve\n','Reuse does not rebuild or mutate a database.');
  const restartBody=startBody.replace(`-Port ${port}`,`-Port ${port} -Restart`);
  await writeFile(path.join(scripts,'build.mjs'),'process.exit(23);');
  assert.notEqual((await runPs(restartBody)).code,0,'Build failure must surface.');
  assert.equal((await fetch(`http://127.0.0.1:${port}/api/info`)).status,200,'A failed build preserves the running origin.');
  await writeFile(path.join(scripts,'build.mjs'),build);
  await writeFile(path.join(scripts,'backup.mjs'),'process.exit(24);');
  assert.notEqual((await runPs(restartBody)).code,0,'Backup failure must surface.');
  assert.equal((await fetch(`http://127.0.0.1:${port}/api/info`)).status,200,'A failed backup preserves the running origin.');
  await writeFile(path.join(scripts,'backup.mjs'),backup);
  const restarted=await resultOf(restartBody);
  ownedIds.add(restarted.serverId);
  assert.notEqual(restarted.serverId,first.serverId,'Restart only replaces the verified test workspace instance.');
  const legacy=await resultOf(`$p=[pscustomobject]@{Name='node.exe';CommandLine='node scripts/dev.mjs';ProcessId=123;ExecutablePath=''};$default=Test-WorkbenchProcess -Process $p -WebRoot ${quote(sandbox)} -NodePath 'node';$approved=Test-WorkbenchProcess -Process $p -WebRoot ${quote(sandbox)} -NodePath 'node' -ExpectedProcessId 123;Write-Output ('@@RESULT@@'+(@{default=$default;approved=$approved}|ConvertTo-Json -Compress))`);
  assert.equal(legacy.default,false,'Ambiguous legacy working directories cannot be stopped automatically.');
  assert.equal(legacy.approved,true,'One-time explicitly identified legacy PID can migrate.');
  const deceptive=await resultOf(`$p=[pscustomobject]@{Name='node.exe';CommandLine=('node "'+${quote(path.join(sandbox,'scripts/dev.mjs.backup'))}+'"');ProcessId=123;ExecutablePath=''};Write-Output ('@@RESULT@@'+(Test-WorkbenchProcess -Process $p -WebRoot ${quote(sandbox)} -NodePath 'node'|ConvertTo-Json -Compress))`);
  assert.equal(deceptive,false,'A similarly named foreign script is never treated as the origin.');
  const config=path.join(sandbox,'config with spaces.yml');
  await writeFile(config,'tunnel: YOUR_TUNNEL_ID\ncredentials-file: missing.json\n');
  assert.equal(await resultOf(`Write-Output ('@@RESULT@@'+(Test-WorkbenchTunnelConfig -ConfigPath ${quote(config)} -WebRoot ${quote(sandbox)}|ConvertTo-Json -Compress))`),false);
  await writeFile(path.join(sandbox,'dummy credential.json'),'DO NOT PRINT OR OPEN THIS CONTENT');
  await writeFile(config,`tunnel: test-tunnel\ncredentials-file: '${path.join(sandbox,'dummy credential.json')}'\n`);
  assert.equal(await resultOf(`Write-Output ('@@RESULT@@'+(Test-WorkbenchTunnelConfig -ConfigPath ${quote(config)} -WebRoot ${quote(sandbox)}|ConvertTo-Json -Compress))`),true);
  const health=await resultOf(`Write-Output ('@@RESULT@@'+(Get-WorkbenchHealth -Url 'http://127.0.0.1:1' -TimeoutSeconds 1|ConvertTo-Json -Compress))`);
  assert.equal(health,false,'Unreachable origins cannot be reported healthy.');
  await writeFile(path.join(scripts,'dev.mjs'),'process.exit(25);');
  const badRuntime=await runPs(restartBody);
  assert.notEqual(badRuntime.code,0,'A process that exits before health must report a startup failure.');
  assert.equal(await resultOf(`Write-Output ('@@RESULT@@'+(@(Get-WorkbenchListeners -Port ${port}).Count|ConvertTo-Json -Compress))`),0,'Unhealthy newly started processes do not keep the test port occupied.');
  const launcher=path.join(sandbox,'isolated launcher');
  await mkdir(path.join(launcher,'web/scripts'),{recursive:true});
  await writeFile(path.join(launcher,'web/scripts/start-services.ps1'),"function Start-WorkbenchServices { throw 'ISOLATED_STARTUP_FAILURE' }\r\n",'utf8');
  const launcherSource=await readFile(path.join(project,'..','启动全部云服务.ps1'),'utf8');
  const launcherPath=path.join(launcher,'启动全部云服务.ps1');
  await writeFile(launcherPath,launcherSource,'utf8');
  const errorReport=await runPs(`& ${quote(launcherPath)} -NonInteractive`);
  assert.equal(errorReport.code,1,'Double-click launcher failures propagate a nonzero exit code.');
  assert.ok(errorReport.stdout.includes('ISOLATED_STARTUP_FAILURE'),'Launcher reports the concrete error without swallowing it.');
  assert.ok((await readFile(path.join(launcher,'web/.local/startup.err.log'),'utf8')).includes('ISOLATED_STARTUP_FAILURE'),'Launcher persists an actionable error log.');
  console.log('PASS startup lifecycle: Windows PowerShell 5, spaces, safe port ownership, backup/build gates, health, idempotency and legacy migration.');
} finally {
  if(foreign) foreign.kill();
  for(const processId of ownedIds) await runPs(`$p=Get-CimInstance Win32_Process -Filter 'ProcessId=${processId}' -ErrorAction SilentlyContinue;if($p -and (Test-WorkbenchProcess -Process $p -WebRoot ${quote(sandbox)} -NodePath ${quote(process.execPath)})){Stop-Process -Id ${processId} -ErrorAction SilentlyContinue}`);
  await rm(sandbox,{recursive:true,force:true});
}
