import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// This creates the one-file Node server used by the Windows release. The
// normal development entry point remains unchanged; this bundle only removes
// the need to ship thousands of node_modules files in the release zip.
const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(webRoot);
process.env.ESBUILD_WORKER_THREADS = '0';

// Generate the regular web bundle first so the release always contains the
// current UI and embedded SOP documents.
await import('./build.mjs');
const { build } = await import('esbuild');
await mkdir('dist/release', { recursive: true });
await build({
  absWorkingDir: webRoot,
  entryPoints: ['./scripts/dev.mjs'],
  outfile: 'dist/release/server.mjs',
  bundle: true,
  packages: 'bundle',
  format: 'esm',
  platform: 'node',
  target: 'node24',
  external: ['node:*'],
  banner: {
    js: '// Fengru Workbench portable server; generated by scripts/release-build.mjs\n'
  }
});
console.log('Portable server bundle built.');
